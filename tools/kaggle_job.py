#!/usr/bin/env python3
"""Write a Kaggle script kernel that trains one adapter from a fixed commit.

The kernel clones this public repository at exactly that commit, installs the
training requirements and runs training/train_lora.py. Its output folder
(/kaggle/working) then holds the PEFT adapter in adapter/ and manifest.json;
the GitHub runner converts it to GGUF. No credentials are
written into the kernel; the repository is public.

    python tools/kaggle_job.py --dir job --owner USER --repo OWNER/REPO \
        --commit SHA --base Qwen/Qwen2.5-1.5B-Instruct --name vyvy-1.5b-v1

Prints the kernel id (owner/slug) on stdout.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

BASES = ("Qwen/Qwen2.5-1.5B-Instruct", "Qwen/Qwen2.5-7B-Instruct")
NAME = re.compile(r"^[a-z0-9][a-z0-9.-]{0,60}$")
SHA = re.compile(r"^[0-9a-f]{40}$")
REPO = re.compile(r"^[A-Za-z0-9-]+/[A-Za-z0-9._-]+$")

ENTRY = '''\
# Generated by tools/kaggle_job.py. Runs on Kaggle, not in the repository.
import os
import subprocess
import sys

REPO = {repo}
COMMIT = {commit}
BASE = {base}
NAME = {name}
EPOCHS = {epochs}
SWEEP = {sweep}
BUDGET = {budget}
BATCH = {batch}
ACCUM = {accum}
SRC = "/tmp/vyvy"


# One GPU only: with two visible GPUs the trainer wraps the model in DataParallel,
# which breaks 4-bit layers and gains nothing for a small LoRA run.
ENV = dict(os.environ, CUDA_VISIBLE_DEVICES="0", VYVY_COMMIT=COMMIT)


def sh(*args):
    print("+", " ".join(args), flush=True)
    subprocess.run(args, check=True, env=ENV)


sh("git", "clone", "--quiet", "https://github.com/" + REPO, SRC)
sh("git", "-C", SRC, "checkout", "--quiet", COMMIT)
sh(sys.executable, "-m", "pip", "install", "-q", "-r", SRC + "/training/requirements.txt")
# GGUF conversion happens on the GitHub runner (tools/convert_adapter.py).
sh(sys.executable, SRC + "/training/train_lora.py", "--base", BASE, "--name", NAME,
   "--epochs", EPOCHS, "--out", "/kaggle/working", "--no-gguf", "--sweep", SWEEP, "--time-budget", BUDGET,
   "--batch", BATCH, "--grad-accum", ACCUM)
'''


SYNTH_SLUG = "vyvy-synth-teacher"
SYNTH_ENTRY = '''\
# Generated by tools/kaggle_job.py. Runs on Kaggle, not in the repository.
import os
import subprocess
import sys

REPO = {repo}
COMMIT = {commit}
ROUND = {round}
SRC = "/tmp/vyvy"
ENV = dict(os.environ, CUDA_VISIBLE_DEVICES="0", HF_HOME="/tmp/hf", VYVY_COMMIT=COMMIT)


def sh(*args):
    print("+", " ".join(args), flush=True)
    subprocess.run(args, check=True, env=ENV)


sh("git", "clone", "--quiet", "https://github.com/" + REPO, SRC)
sh("git", "-C", SRC, "checkout", "--quiet", COMMIT)
sh(sys.executable, "-m", "pip", "install", "-q", "-r", SRC + "/training/requirements.txt")
sh(sys.executable, SRC + "/training/synthesize.py", "--out", "/kaggle/working", "--round", ROUND)
'''


def write_synth_job(folder: Path, owner: str, repo: str, commit: str, round_: str) -> str:
    """Kernel that runs training/synthesize.py (teacher model) at a fixed commit."""
    if not SHA.match(commit):
        raise SystemExit("commit must be a full 40-character SHA")
    if not REPO.match(repo):
        raise SystemExit("repo must be OWNER/NAME")
    if not re.match(r"^[A-Za-z0-9_-]+$", owner):
        raise SystemExit("owner must be a Kaggle user name")
    if not re.match(r"^[0-9]{4}-W[0-9]{2}$", round_):
        raise SystemExit("round must look like 2026-W45")
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "synth.py").write_text(SYNTH_ENTRY.format(repo=json.dumps(repo), commit=json.dumps(commit),
                                                       round=json.dumps(round_)),
                                     encoding="utf-8")
    write_metadata(folder, f"{owner}/{SYNTH_SLUG}", SYNTH_SLUG, "synth.py")
    return f"{owner}/{SYNTH_SLUG}"


def write_metadata(folder: Path, kid: str, slug: str, code_file: str) -> None:
    (folder / "kernel-metadata.json").write_text(json.dumps({
        "id": kid,
        "title": slug,
        "code_file": code_file,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "machine_shape": "NvidiaTeslaT4",
        # Keep the container of the kernel's first version: an image update cannot
        # change the environment under a running pipeline.
        "docker_image_pinning_type": "original",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }, indent=1) + "\n", encoding="utf-8")


def kernel_slug(base: str) -> str:
    return "vyvy-train-" + re.sub(r"[^a-z0-9]+", "-", base.split("/")[-1].lower()).strip("-")


def write_job(folder: Path, owner: str, repo: str, commit: str, base: str, name: str, epochs: float,
              sweep: str = "", budget: float = 0, batch: int = 8, accum: int = 2) -> str:
    if base not in BASES:
        raise SystemExit(f"base must be one of {BASES}")
    if not NAME.match(name):
        raise SystemExit("name: lowercase letters, digits, '.' and '-', at most 61 characters")
    if not SHA.match(commit):
        raise SystemExit("commit must be a full 40-character SHA")
    if not REPO.match(repo):
        raise SystemExit("repo must be OWNER/NAME")
    if not re.match(r"^[A-Za-z0-9_-]+$", owner):
        raise SystemExit("owner must be a Kaggle user name")
    if not 0 < epochs <= 10:
        raise SystemExit("epochs must be between 0 and 10")
    if not re.match(r"^[a-z0-9=.,;e+-]*$", sweep):
        raise SystemExit("sweep may only contain keys, numbers and = , ;")
    if not (1 <= batch <= 64 and 1 <= accum <= 64):
        raise SystemExit("batch and grad accumulation must be between 1 and 64")
    if not 0 <= budget <= 660:
        raise SystemExit("budget must be between 0 and 660 minutes (Kaggle sessions end after 12 h)")

    slug = kernel_slug(base)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "train.py").write_text(ENTRY.format(
        repo=json.dumps(repo), commit=json.dumps(commit), base=json.dumps(base),
        name=json.dumps(name), epochs=json.dumps(f"{epochs:g}"), sweep=json.dumps(sweep),
        budget=json.dumps(f"{budget:g}"), batch=json.dumps(str(batch)), accum=json.dumps(str(accum)),
    ), encoding="utf-8")
    write_metadata(folder, f"{owner}/{slug}", slug, "train.py")
    return f"{owner}/{slug}"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Write a Kaggle kernel that trains one Vyvy AI adapter")
    p.add_argument("--dir", type=Path, required=True)
    p.add_argument("--owner", required=True, help="Kaggle user name")
    p.add_argument("--repo", required=True, help="GitHub OWNER/NAME of this repository")
    p.add_argument("--commit", required=True, help="full commit SHA to train from")
    p.add_argument("--base", choices=BASES)
    p.add_argument("--name", help="adapter name, also the release tag")
    p.add_argument("--synth", action="store_true", help="write the teacher synthesis kernel instead")
    p.add_argument("--round", default="", help="synthesis round (ISO week), with --synth")
    p.add_argument("--epochs", type=float, default=3)
    p.add_argument("--sweep", default="", help='e.g. "rank=16,8,32;lr=2e-4,1e-4,5e-4"')
    p.add_argument("--budget", type=float, default=0, help="minutes for the whole sweep")
    p.add_argument("--batch", type=int, default=8)
    p.add_argument("--grad-accum", type=int, default=2)
    args = p.parse_args(argv)
    if args.synth:
        print(write_synth_job(args.dir, args.owner, args.repo, args.commit, args.round))
        return 0
    if not (args.base and args.name):
        p.error("--base and --name are required for a training kernel")
    print(write_job(args.dir, args.owner, args.repo, args.commit, args.base, args.name, args.epochs,
                    args.sweep, args.budget, args.batch, args.grad_accum))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
